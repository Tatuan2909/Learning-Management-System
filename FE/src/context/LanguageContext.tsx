interface LanguageContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: keyof typeof translations.VI) => string;
}

const LanguageContext = createContext<LanguageContextType>({
  language: 'VI',
  setLanguage: () => {},
  t: (key) => translations.VI[key] || key
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(() => {
    return (localStorage.getItem('lms_language') as Language) || 'VI';
  });

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    localStorage.setItem('lms_language', lang);
  };

  const t = (key: keyof typeof translations.VI): string => {
    const langDict = translations[language] || translations.VI;
    return langDict[key] || translations.VI[key] || (key as string);
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
